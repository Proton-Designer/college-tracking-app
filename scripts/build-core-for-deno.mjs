#!/usr/bin/env node
/**
 * Generates a Deno-importable mirror of packages/core at
 * supabase/functions/_shared/core/ -- L7's nightly/weekly analysis edge functions need
 * the real domain engine (risk traces, planning-execution diagnosis, bounce-back,
 * friction distribution), not a hand-maintained reimplementation that could drift from
 * the one Node/bundler consumers use.
 *
 * Why a generated mirror instead of importing packages/core directly: confirmed live
 * that Supabase's actual Edge Runtime (supabase-edge-runtime, not just the Deno CLI)
 * rejects packages/core's extensionless relative imports outright -- "Module not
 * found ... types" -- even with deno.json's `unstable: ["sloppy-imports"]` set (that flag
 * satisfies `deno check` via the full Deno CLI, but the deployed runtime doesn't honor
 * it the same way). packages/core's source must stay extensionless for Node/bundler
 * consumers (D4 -- extensionless is what Turbopack/Metro require), so a transform step
 * is unavoidable if Deno is going to consume the same source.
 *
 * Mechanical only: copies every packages/core/src/*.ts file byte-for-byte except for
 * appending a literal `.ts` to same-package relative import/export specifiers. Nothing
 * about the logic changes. Regenerate after any packages/core edit: `npm run build:core-for-deno`.
 * Not run automatically on every packages/core change (no watcher) -- if the nightly
 * function's numbers ever look stale relative to packages/core, this is the first thing
 * to check.
 */
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const SRC_ROOT = 'packages/core/src';
const OUT_ROOT = 'supabase/functions/_shared/core';

// Matches a relative specifier (./... or ../...) with no extension already present.
const RELATIVE_IMPORT = /((?:from|import)\s*\(?\s*['"])(\.[^'"]*?)(['"])/g;

function needsExtension(specifier) {
  return !/\.[a-zA-Z0-9]+$/.test(specifier);
}

function rewrite(source) {
  return source.replace(RELATIVE_IMPORT, (match, prefix, specifier, quote) => {
    if (!needsExtension(specifier)) return match;
    return `${prefix}${specifier}.ts${quote}`;
  });
}

function walk(dir, fn) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) {
      walk(full, fn);
      continue;
    }
    if (entry.endsWith('.test.ts')) continue; // Deno never needs the Node-side test files.
    if (!entry.endsWith('.ts')) continue;
    fn(full);
  }
}

if (existsSync(OUT_ROOT)) rmSync(OUT_ROOT, { recursive: true });
mkdirSync(OUT_ROOT, { recursive: true });

writeFileSync(
  join(OUT_ROOT, 'README.md'),
  `# Generated — do not edit by hand

Every file in this directory is a mechanical, extension-fixed copy of \`packages/core/src\`
(see \`scripts/build-core-for-deno.mjs\` for exactly what the transform does — it appends
\`.ts\` to same-package relative imports and changes nothing else). The Supabase Edge
Runtime cannot resolve \`packages/core\`'s extensionless imports directly (confirmed live —
see decision D16 in \`.brain/memory/decisions.md\`), and \`packages/core\`'s source must stay
extensionless for Node/bundler consumers, so this mirror exists to give Deno a resolvable
copy of the same domain engine without a second, hand-maintained implementation.

**If you need to change domain logic, edit \`packages/core/src\`, not a file here.** Then:

\`\`\`bash
npm run build:core-for-deno
\`\`\`

\`npm run verify\` (\`check:core-mirror\`) fails loudly if this directory is stale relative to
\`packages/core/src\` — it does not auto-regenerate, on purpose: a stale mirror silently
diverges the nightly/weekly report's numbers from what the rest of the product computes
and displays, and that failure mode should never be quiet.
`,
);

let fileCount = 0;
walk(SRC_ROOT, (full) => {
  const relative = full.slice(SRC_ROOT.length + 1);
  const outPath = join(OUT_ROOT, relative);
  mkdirSync(dirname(outPath), { recursive: true });
  const source = readFileSync(full, 'utf8');
  const header = `// GENERATED by scripts/build-core-for-deno.mjs from ${full} -- do not edit directly.\n// Regenerate with \`npm run build:core-for-deno\` after any packages/core change.\n\n`;
  writeFileSync(outPath, header + rewrite(source));
  fileCount++;
});

console.log(`Wrote ${fileCount} files to ${OUT_ROOT}`);
